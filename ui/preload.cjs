const { contextBridge, ipcRenderer } = require('electron');

const call = channel => input => ipcRenderer.invoke(channel, input);
contextBridge.exposeInMainWorld('buddy', {
  info: call('settings:info'),
  saveSettings: call('settings:save'),
  testApi: call('settings:test'),
  documents: call('documents:list'),
  importDocuments: call('documents:import'),
  passages: call('documents:passages'),
  search: call('documents:search'),
  deleteDocument: call('documents:delete'),
  facts: call('facts:list'),
  draft: call('facts:draft'),
  addFact: call('facts:add'),
  updateFact: call('facts:update'),
  sessions: call('sessions:list'),
  session: call('sessions:get'),
  create: call('sessions:create'),
  deleteSession: call('sessions:delete'),
  applications: call('applications:list'),
  applicationStatuses: call('applications:statuses'),
  saveApplication: call('applications:save'),
  deleteApplication: call('applications:delete'),
  prepare: call('sessions:prepare'),
  consultationTools: call('sessions:consultation-tools'),
  openSource: call('sessions:open-source'),
  answer: call('sessions:answer'),
  review: call('sessions:review'),
  cancel: call('sessions:cancel'),
  openLive: call('live:open'),
  onLiveChanged: listener => { ipcRenderer.on('live:changed', () => listener()); },
  onDelta: listener => ipcRenderer.on('sessions:delta', (_event, item) => listener(item)),
  onTool: listener => { ipcRenderer.on('sessions:tool', (_event, item) => listener(item)); },
});
